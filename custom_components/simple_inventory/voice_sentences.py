"""Voice sentences for local Assist: the bundled template and the generated names file.

The bundled template (data/custom_sentences/<lang>/simple_inventory.yaml) is copied into
<config>/custom_sentences/<lang>/ when the user asks for it. Its inventory slot accepts
only the names in the ``simple_inventory_name`` list, which the template declares empty:
next to every installed template the integration keeps simple_inventory_names.yaml, which
lists the enabled inventories. Home Assistant merges the files of a language directory and
concatenates their lists, so the load order does not matter, and a template left without a
names file matches nothing instead of failing.

A closed list rather than a wildcard because Home Assistant prefers custom sentences over
its built-in ones: "add {item} to {inventory}" with a wildcard took over "add milk to my
shopping list" and "add 5 minutes to my timer".
"""

from __future__ import annotations

import asyncio
import hashlib
import logging
import os
import re
import shutil
from collections.abc import Callable, Iterable
from pathlib import Path

from homeassistant.core import HomeAssistant
from homeassistant.exceptions import HomeAssistantError
from homeassistant.util import language as language_util
from homeassistant.util.hass_dict import HassKey
from homeassistant.util.yaml import dump as yaml_dump

from .const import CONF_NAME, DOMAIN
from .entries import enabled_inventory_entries
from .repairs import (
    async_create_voice_sentences_outdated_issue,
    async_delete_voice_sentences_outdated_issue,
)

_LOGGER = logging.getLogger(__name__)

_BUNDLED_ROOT = Path(__file__).parent / "data" / "custom_sentences"
_FILENAME = "simple_inventory.yaml"
_NAMES_FILENAME = "simple_inventory_names.yaml"
NAMES_LIST = "simple_inventory_name"

# sha256 of every template an earlier release installed (inventory as a wildcard). An
# installed copy still byte-identical to one is replaced with the current template; an
# edited one is left alone and reported as a repair issue.
_SUPERSEDED_TEMPLATES = frozenset(
    {
        "2147ec332c7dd5664413d9d53d5c9940530f74bc257fb1b07a9aeac080f40405",  # 0.6.0, en
    }
)

_NAMES_HEADER = (
    "# Generated by Simple Inventory: the inventory names its voice sentences accept.\n"
    "# Rewritten whenever an inventory is added, renamed, enabled or removed. Do not edit.\n"
)

# hassil template syntax; a name containing it would be parsed as a template.
_TEMPLATE_SYNTAX = re.compile(r"[\[\](){}<>|]")

_SYNC_LOCK: HassKey[asyncio.Lock] = HassKey(f"{DOMAIN}_voice_sentences_lock")


def _discover_bundled_languages() -> frozenset[str]:
    """Return the set of languages this package ships a sentence template for."""
    if not _BUNDLED_ROOT.is_dir():
        return frozenset()
    return frozenset(
        child.name
        for child in _BUNDLED_ROOT.iterdir()
        if child.is_dir() and (child / _FILENAME).is_file()
    )


_BUNDLED_LANGUAGES = _discover_bundled_languages()


def _matched_bundled_language(language: str) -> str | None:
    """Resolve `language` to a bundled language key."""
    matches = language_util.matches(language, _BUNDLED_LANGUAGES)
    return matches[0] if matches else None


def can_offer_voice_sentences(hass: HomeAssistant) -> bool:
    """Return True if a bundled sentence template matches hass.config.language."""
    return _matched_bundled_language(hass.config.language) is not None


# Slovenian inflects nouns by case ("v kuhinji", "v shrambo"), which a closed list only
# matches if it lists the forms. Common endings of the last word; irregular names (a
# fleeting vowel, adjective + noun) still work in the form they are stored in.
_SL_VOWEL_ENDINGS = {
    "a": ("a", "e", "i", "o", "ama", "ah", "ami"),
    "o": ("o", "a", "u", "om", "i", "ih"),
    "e": ("e", "a", "u", "em", "i", "ih"),
}
_SL_CONSONANT_ENDINGS = ("", "a", "u", "om", "i", "e", "ov", "ih")


def _slovenian_forms(name: str) -> list[str]:
    head, _, last = name.rpartition(" ")
    final = last[-1:].lower()
    if final in _SL_VOWEL_ENDINGS:
        stem, endings = last[:-1], _SL_VOWEL_ENDINGS[final]
    elif final.isalpha() and final not in "aeiou":
        stem, endings = last, _SL_CONSONANT_ENDINGS
    else:
        return [name]
    prefix = f"{head} " if head else ""
    return list(dict.fromkeys([name, *(f"{prefix}{stem}{ending}" for ending in endings)]))


_SPOKEN_FORMS: dict[str, Callable[[str], list[str]]] = {"sl": _slovenian_forms}


def names_yaml(language: str, names: Iterable[str]) -> str:
    """The names file for *language*: every spoken form of each name, mapped to the name."""
    forms = _SPOKEN_FORMS.get(language, lambda name: [name])
    values: list[dict[str, str]] = []
    for name in sorted(set(names), key=str.casefold):
        spoken = " ".join(_TEMPLATE_SYNTAX.sub(" ", name).split())
        if spoken:
            values.extend({"in": form, "out": name} for form in forms(spoken))
    document = {"language": language, "lists": {NAMES_LIST: {"values": values}}}
    return _NAMES_HEADER + yaml_dump(document)


def _copy_template(source: Path, target: Path) -> None:
    """Blocking, exclusive-create file copy; must only be called via the executor."""
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, "xb") as dest, open(source, "rb") as src:
        shutil.copyfileobj(src, dest)


def _write_replacing(target: Path, content: bytes) -> None:
    """Replace *target* in one step; the temp name doesn't end in .yaml, so HA skips it."""
    temporary = target.with_name(f".{target.name}.tmp")
    temporary.write_bytes(content)
    os.replace(temporary, target)


def _sync_files(root: Path, names: list[str]) -> tuple[list[str], list[str]]:
    """Blocking part of the sync: (languages whose files changed, outdated template paths)."""
    changed: list[str] = []
    outdated: list[str] = []
    for language in sorted(_BUNDLED_LANGUAGES):
        template = root / language / _FILENAME
        if not template.is_file():
            continue
        content = template.read_bytes()
        if hashlib.sha256(content).hexdigest() in _SUPERSEDED_TEMPLATES:
            _write_replacing(template, (_BUNDLED_ROOT / language / _FILENAME).read_bytes())
            changed.append(language)
        elif NAMES_LIST.encode() not in content:
            outdated.append(str(template))

        names_file = template.with_name(_NAMES_FILENAME)
        wanted = names_yaml(language, names).encode()
        if not names_file.is_file() or names_file.read_bytes() != wanted:
            _write_replacing(names_file, wanted)
            if language not in changed:
                changed.append(language)
    return changed, outdated


async def _async_reload(hass: HomeAssistant, language: str) -> None:
    try:
        await hass.services.async_call(
            "conversation", "reload", {"language": language}, blocking=True
        )
    except HomeAssistantError as err:
        _LOGGER.warning(
            "Updated the %s voice sentences but failed to reload custom sentences "
            "(they will take effect on next restart): %s",
            language,
            err,
        )


async def async_sync_voice_sentences(
    hass: HomeAssistant, reload_languages: Iterable[str] = ()
) -> None:
    """Bring every installed template's names file in line with the enabled inventories.

    Also replaces installed templates an earlier release shipped unchanged and raises a
    repair issue for edited ones still in the old format. Reloads the custom sentences of
    each language whose files changed, plus *reload_languages*.
    """
    async with hass.data.setdefault(_SYNC_LOCK, asyncio.Lock()):
        names = [str(entry.data[CONF_NAME]) for entry in enabled_inventory_entries(hass)]
        try:
            changed, outdated = await hass.async_add_executor_job(
                _sync_files, Path(hass.config.path("custom_sentences")), names
            )
        except OSError as err:
            _LOGGER.warning("Could not update the voice sentence files: %s", err)
            return

        if outdated:
            async_create_voice_sentences_outdated_issue(hass, outdated)
        else:
            async_delete_voice_sentences_outdated_issue(hass)

        for language in sorted({*changed, *reload_languages}):
            await _async_reload(hass, language)


async def async_install_voice_sentences(hass: HomeAssistant) -> bool:
    """Install the bundled sentence template matching hass.config.language."""
    language = hass.config.language
    matched_language = _matched_bundled_language(language)
    if matched_language is None:
        return False

    source = _BUNDLED_ROOT / matched_language / _FILENAME
    target = Path(hass.config.path("custom_sentences", matched_language, _FILENAME))

    if await hass.async_add_executor_job(target.is_file):
        return True

    try:
        await hass.async_add_executor_job(_copy_template, source, target)
    except FileExistsError:
        return True
    except OSError as err:
        _LOGGER.warning("Could not install example voice sentences: %s", err)
        return False

    await async_sync_voice_sentences(hass, reload_languages=(matched_language,))
    return True
